from __future__ import annotations

from typing import Any

from mcp.server.fastmcp import FastMCP

from .config import settings
from .gateway import JavaGatewayClient


gateway = JavaGatewayClient()
mcp = FastMCP(
    "flmh-demo-tools",
    host=settings.mcp_host,
    port=settings.mcp_port,
)


@mcp.tool()
async def search_products(
    region: str,
    keyword: str = "",
    category: str = "",
    max_price: float | None = None,
) -> dict[str, Any]:
    """Query products through the local Java Gateway; source is reported by that service."""
    return await gateway.search_products(
        region=region,
        keyword=keyword or None,
        category=category or None,
        max_price=max_price,
    )


@mcp.tool()
async def create_content_quote(
    product_id: str,
    content_type: str,
    brief: str,
    budget_max: float | None = None,
) -> dict[str, Any]:
    """Calculate a local Demo quote. This does not create or submit a content task."""
    return await gateway.create_content_quote({
        "productId": product_id,
        "contentType": content_type,
        "brief": brief,
        "budgetMax": budget_max,
    })


@mcp.tool()
async def confirm_content_quote(quote_id: str, confirmed: bool) -> dict[str, Any]:
    """Record explicit user confirmation for a quote before task creation."""
    if confirmed is not True:
        raise ValueError("quote confirmation must be explicitly true")
    return await gateway.confirm_content_quote(quote_id, confirmed=True)


@mcp.tool()
async def create_content_task(
    quote_id: str,
    product_id: str,
    content_type: str,
    brief: str,
    idempotency_key: str,
) -> dict[str, Any]:
    """Create or return the idempotent content task for a confirmed quote."""
    if not idempotency_key.startswith("demo-"):
        raise ValueError("idempotency_key must be generated by the Demo Agent")
    return await gateway.create_content_task({
        "quoteId": quote_id,
        "productId": product_id,
        "contentType": content_type,
        "brief": brief,
        "idempotencyKey": idempotency_key,
    }, idempotency_key=idempotency_key)


@mcp.tool()
async def get_content_task(task_id: str) -> dict[str, Any]:
    """Read the current content task status from the local Java Gateway."""
    return await gateway.get_content_task(task_id)


def main() -> None:
    mcp.run(transport="streamable-http")


if __name__ == "__main__":
    main()
